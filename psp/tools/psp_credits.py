"""English overlay for the PSP ending staff roll (movie 006).

The PSP roll is not the PS2 one: it adds the porting staff (Alpha System,
Namco Tales Studio, Namco Bandai) and orders and spells some names
differently, so it has its own table, psp_credits.tsv, in the format of
ps2/movies/ending_credits.tsv:

    id, t0 (s, the row's top reaches the bottom edge), speed (px/s, upward),
    height (px), segments (x0-x1;...), japanese, english

english is KEEP for Latin text and logos; two columns are "left / right";
a trailing "?" marks an unverified name reading and is not drawn.

The rows were measured on the PSP video itself: the roll scrolls at a
constant 37.8 px/s, so a slit scan of the screen line y=136 over time (one
line per frame, stacked) is the whole roll as one still picture, where every
row was located (its top, height and text spans) and read. Each English
row is drawn on a black box over the Japanese one and moves with it; the
final "Produced by" card gets its company line the same way, plus the
Green Gel card below it, both with the card's fades.

    python psp_credits.py            # write psp_credits.ass
    python psp_credits.py --check    # fail if psp_credits.ass is stale
"""
import argparse
import csv
import importlib.util
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
TSV = os.path.join(HERE, 'psp_credits.tsv')
OUT = os.path.join(HERE, 'psp_credits.ass')
FONT_FILE = os.path.join(ROOT, 'ps2', 'movies', 'fonts', 'Ubuntu-Bold.ttf')

W, H = 480, 272
PAD_X, PAD_Y = 3, 3
TEXT_DY = -3
CREDIT_RIGHT = 272  # the art panel starts at x=276
COLUMN_GAP = 6
MIN_SCALE_X = 50
EXPECTED_ROWS = 364

# final card: "Produced by" over the company line, measured on the movie
CARD_LINE = (90, 143, 394, 161)  # x0, y0, x1, y1 of 株式会社バンダイナムコゲームス
CARD_START, CARD_END = 425.2, 437.94
CARD_FADE = (2800, 2200)

HEADER = """[Script Info]
; Tales of Destiny 2 (PSP) ending staff roll, English overlay
; Generated by psp/tools/psp_credits.py from psp_credits.tsv
ScriptType: v4.00+
PlayResX: 480
PlayResY: 272
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.601

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Credit,Ubuntu,16,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,0.9,0,7,0,0,0,1
Style: Box,Ubuntu,16,&H00000000,&H00000000,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,7,0,0,0,1
Style: Card,Ubuntu,15,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,-1,0,0,0,100,100,1,0,1,1.0,0,8,0,0,0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


def _ps2_generator():
    path = os.path.join(ROOT, 'ps2', 'movies', 'credits_ass.py')
    spec = importlib.util.spec_from_file_location('credits_ass', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def read_rows():
    with open(TSV, encoding='utf-8', newline='') as f:
        rows = list(csv.DictReader(f, delimiter='\t'))
    if len(rows) != EXPECTED_ROWS:
        raise ValueError('expected %d credit rows, found %d' % (EXPECTED_ROWS, len(rows)))
    previous = -1.0
    for i, row in enumerate(rows):
        if int(row['id']) != i:
            raise ValueError('row %d has id %r' % (i, row['id']))
        t0, speed, height = float(row['t0']), float(row['speed']), int(row['height'])
        if t0 < previous or speed <= 0 or height <= 0:
            raise ValueError('invalid timing or size at row %d' % i)
        previous = t0
        segs = segments(row)
        if any(not 0 <= a <= b < W for a, b in segs) or any(x[1] >= y[0] for x, y in zip(segs, segs[1:])):
            raise ValueError('bad segments at row %d' % i)
    return rows


def segments(row):
    return [tuple(int(v) for v in s.split('-')) for s in row['segments'].split(';')]


def texts(row):
    parts = [t.strip().rstrip('?').strip() for t in row['english'].split(' / ')]
    if any(not t or any(c in t for c in '{}\\') for t in parts):
        raise ValueError('row %s has an empty or unsafe text' % row['id'])
    return parts


def events(metrics):
    out = []
    for row in read_rows():
        if row['english'] == 'KEEP':
            continue
        t0, speed, height = float(row['t0']), float(row['speed']), int(row['height'])
        segs, parts = segments(row), texts(row)
        if len(segs) != len(parts):
            raise ValueError('row %s: %d segments, %d texts' % (row['id'], len(segs), len(parts)))
        start = t0
        end = t0 + (H + height + 2 * PAD_Y) / speed
        y0, y1 = H, H - speed * (end - start)
        for i, ((left, right), text) in enumerate(zip(segs, parts)):
            bw, bh = right - left + 2 * PAD_X, height + 2 * PAD_Y
            out.append((0, start, end, 'Box',
                        '{\\an7\\move(%d,%.1f,%d,%.1f)\\p1\\bord0\\shad0\\1c&H000000&}m 0 0 l %d 0 l %d %d l 0 %d{\\p0}'
                        % (left - PAD_X, y0 - PAD_Y, left - PAD_X, y1 - PAD_Y, bw, bw, bh, bh)))
            size = height + 3
            boundary = segs[i + 1][0] - COLUMN_GAP if i + 1 < len(segs) else CREDIT_RIGHT
            available = boundary - left - 2
            natural = metrics.text_width(text, size)
            scale = min(90 if len(segs) == 2 else 100, math.floor(100 * available / natural))
            if scale < MIN_SCALE_X:
                raise ValueError('row %s: %r needs ScaleX=%d' % (row['id'], text, scale))
            tag = '\\fscx%d' % scale if scale != 100 else ''
            out.append((1, start, end, 'Credit', '{\\an7\\move(%d,%.1f,%d,%.1f)\\fs%d%s}%s'
                        % (left, y0 + TEXT_DY, left, y1 + TEXT_DY, size, tag, text)))
    x0, y0, x1, y1 = CARD_LINE
    fade = '\\fad(%d,%d)' % CARD_FADE
    bw, bh = x1 - x0 + 2 * PAD_X, y1 - y0 + 2 * PAD_Y
    out.append((0, CARD_START, CARD_END, 'Box', '{\\an7\\pos(%d,%d)%s\\p1\\bord0\\shad0\\1c&H000000&}m 0 0 l %d 0 l %d %d l 0 %d{\\p0}'
                % (x0 - PAD_X, y0 - PAD_Y, fade, bw, bw, bh, bh)))
    out.append((1, CARD_START, CARD_END, 'Card', '{\\an8\\pos(%d,%d)%s\\fs18}NAMCO BANDAI Games Inc.'
                % ((x0 + x1) // 2, y0 - 1, fade)))
    out.append((1, CARD_START, CARD_END, 'Card', '{\\an8\\pos(240,214)%s}Green Gel Group\\NEnglish Patch' % fade))
    return out


def render():
    gen = _ps2_generator()
    metrics = gen.TrueTypeMetrics(gen.Path(FONT_FILE))
    lines = [HEADER]
    evs = events(metrics)
    for layer, start, end, style, text in evs:
        lines.append('Dialogue: %d,%s,%s,%s,,0,0,0,,%s\n' % (layer, gen.ts(start), gen.ts(end), style, text))
    return ''.join(lines), len(evs)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='fail if psp_credits.ass is not the generated output')
    a = ap.parse_args(argv)
    text, n = render()
    if a.check:
        if not os.path.exists(OUT) or open(OUT, encoding='utf-8').read() != text:
            raise SystemExit('%s is stale; run psp_credits.py' % OUT)
        print('verified %s: %d events' % (OUT, n))
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d events' % (OUT, n))


if __name__ == '__main__':
    main()
